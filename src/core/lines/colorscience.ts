const LOCUS_N = LOCUS_XY.length / 2;

/** D65 white point chromaticity (CIE 15). */
export const D65_X = 0.3127;
export const D65_Y = 0.3290;

// The locus plus the line of purples is a convex polygon containing the white point, so the
// direction from the white point to each vertex is monotonic: a direction -> segment lookup is a
// binary search. Angles are unwrapped and oriented to increase with wavelength.
const locusPhi = new Float64Array(LOCUS_N);
let locusSign = 1;
let locusSpan = 0;
(function initLocus() {
    const ang = (i: number) => Math.atan2(LOCUS_XY[2 * i + 1] - D65_Y, LOCUS_XY[2 * i] - D65_X);
    let d = ang(1) - ang(0);
    if (d > Math.PI) d -= 2 * Math.PI; else if (d < -Math.PI) d += 2 * Math.PI;
    locusSign = d >= 0 ? 1 : -1;
    let prev = ang(0) * locusSign;
    locusPhi[0] = 0;
    for (let i = 1; i < LOCUS_N; i++) {
        const a = ang(i) * locusSign;
        let step = a - prev;
        while (step < -Math.PI) step += 2 * Math.PI;
        while (step > Math.PI) step -= 2 * Math.PI;
        locusPhi[i] = locusPhi[i - 1] + step;
        prev = a;
    }
    locusSpan = locusPhi[LOCUS_N - 1];
})();

export interface Dominant {
    /** Dominant wavelength in nm; negative = complementary wavelength (purple stimulus); 0 = achromatic. */
    wl: number;
    /** Excitation purity 0..1. */
    purity: number;
}

/** Wavelength (nm, interpolated between 1 nm samples) and distance along a ray from white, or null if it misses the locus. */
function rayOnLocus(dx: number, dy: number, out: { wl: number; r: number }): boolean {
    const psi = Math.atan2(dy, dx) * locusSign;
    let t = (psi - Math.atan2(LOCUS_XY[1] - D65_Y, LOCUS_XY[0] - D65_X) * locusSign) % (2 * Math.PI);
    if (t < 0) t += 2 * Math.PI;
    if (t > locusSpan) return false;
    // Binary search for the segment containing t.
    let lo = 0, hi = LOCUS_N - 1;
    while (hi - lo > 1) {
        const mid = (lo + hi) >> 1;
        if (locusPhi[mid] <= t) lo = mid; else hi = mid;
    }
    // Intersect the ray W + r*(dx,dy) with segment V[lo]..V[lo+1].
    const ax = LOCUS_XY[2 * lo] - D65_X, ay = LOCUS_XY[2 * lo + 1] - D65_Y;
    const bx = LOCUS_XY[2 * lo + 2] - D65_X, by = LOCUS_XY[2 * lo + 3] - D65_Y;
    const ex = bx - ax, ey = by - ay;
    const den = dx * ey - dy * ex;
    if (Math.abs(den) < 1e-15) return false;
    const u = (ax * dy - ay * dx) / den;          // position along the segment
    const r = (ax * ey - ay * ex) / den;          // distance along the ray
    out.wl = LOCUS_FIRST_NM + lo + Math.min(1, Math.max(0, u));
    out.r = r;
    return true;
}

const hit = { wl: 0, r: 0 };

/** Dominant (or complementary, negative) wavelength and excitation purity of an xy chromaticity. */
export function xyToDominant(x: number, y: number, out: Dominant = { wl: 0, purity: 0 }): Dominant {
    const dx = x - D65_X, dy = y - D65_Y;
    const dist = Math.hypot(dx, dy);
    if (dist < 1e-9) { out.wl = 0; out.purity = 0; return out; }
    const ux = dx / dist, uy = dy / dist;
    if (rayOnLocus(ux, uy, hit)) {
        out.wl = hit.wl;
        out.purity = Math.min(1, dist / hit.r);
        return out;
    }
    // Purple: the ray meets the line of purples. Report the complementary wavelength.
    if (rayOnLocus(-ux, -uy, hit)) out.wl = -hit.wl; else out.wl = 0;
    // Distance from white to the line of purples along the ray.
    const ax = LOCUS_XY[0] - D65_X, ay = LOCUS_XY[1] - D65_Y;
    const bx = LOCUS_XY[2 * LOCUS_N - 2] - D65_X, by = LOCUS_XY[2 * LOCUS_N - 1] - D65_Y;
    const ex = bx - ax, ey = by - ay;
    const den = ux * ey - uy * ex;
    const r = Math.abs(den) > 1e-15 ? (ax * ey - ay * ex) / den : 1;
    out.purity = Math.min(1, dist / Math.max(1e-9, r));
    return out;
}

/** xy chromaticity of the monochromatic stimulus at a wavelength (nm), interpolated. */
export function locusXY(wl: number, out: [number, number] = [0, 0]): [number, number] {
    let f = Math.min(LOCUS_N - 1.0001, Math.max(0, wl - LOCUS_FIRST_NM));
    const i = Math.floor(f); f -= i;
    out[0] = LOCUS_XY[2 * i] + (LOCUS_XY[2 * i + 2] - LOCUS_XY[2 * i]) * f;
    out[1] = LOCUS_XY[2 * i + 1] + (LOCUS_XY[2 * i + 3] - LOCUS_XY[2 * i + 1]) * f;
    return out;
}

/**
 * Linear sRGB -> XYZ with the matrix exactly as published in IEC 61966-2-1 (four decimals, D65).
 * The Lindbloom-style matrix above carries more digits; the published one is the definition
 * of sRGB and is what the white point (0.3127, 0.3290) is quoted against, so the spectrum code
 * uses it. Near the neutral axis the dominant wavelength is ill-conditioned (it swings by
 * several nm for a change in the fifth decimal of xy), so the choice matters there.
 */
export const SRGB_TO_XYZ_IEC = [0.4124, 0.3576, 0.1805, 0.2126, 0.7152, 0.0722, 0.0193, 0.1192, 0.9505];

/** Dominant wavelength and purity of an sRGB colour (0..255). */
export function rgbToDominant(r: number, g: number, b: number, out: Dominant = { wl: 0, purity: 0 }): Dominant {
    const M = SRGB_TO_XYZ_IEC;
    const rl = srgbToLinear(r), gl = srgbToLinear(g), bl = srgbToLinear(b);
    const X = M[0] * rl + M[1] * gl + M[2] * bl;
    const Y = M[3] * rl + M[4] * gl + M[5] * bl;
    const Z = M[6] * rl + M[7] * gl + M[8] * bl;
    const sum = X + Y + Z;
    if (sum < 1e-9) { out.wl = 0; out.purity = 0; return out; }
    return xyToDominant(X / sum, Y / sum, out);
}
