/**
 * CIE colour science for PRISM: dominant wavelength and excitation purity of an sRGB colour
 * (CIE 15, D65 white point, CIE 1931 2-degree observer).
 *
 *  - sRGB -> XYZ: IEC 61966-2-1:1999 (D65)
 */

// --- sRGB → Linear RGB ---
export function srgbToLinear(c: number): number {
    c /= 255;
    return c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
}

